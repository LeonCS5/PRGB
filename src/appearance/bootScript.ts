import { THEME_TOKEN_NAMES, THEMES, deriveTokens } from './themes';
import { BACKGROUND_STYLES, FONT_PACKS, UI_STYLES } from './types';
import { APPEARANCE_STORAGE_KEY, APPEARANCE_VERSION } from './validate';

// Source of public/appearance-boot.js. That file is generated from here (npm run gen:appearance-boot) and a test
// fails when it is out of date, so the colors it paints before React loads can never drift from themes.ts.
// It must stay a classic script with no dependency: the CSP only allows external scripts from this origin.
export const buildBootScript = (): string => {
  const themes: Record<string, string[]> = {};
  for (const theme of THEMES) {
    if (theme.colors) themes[theme.id] = THEME_TOKEN_NAMES.map((name) => deriveTokens(theme.colors!)[name]);
  }
  return `// GENERATED by scripts/gen-appearance-boot.mjs from src/appearance/themes.ts. Do not edit by hand.
// Paints the saved look on <html> before the first frame; the app applies it again afterwards.
(function () {
  try {
    var N = ${JSON.stringify(THEME_TOKEN_NAMES)};
    var T = ${JSON.stringify(themes)};
    var raw = localStorage.getItem(${JSON.stringify(APPEARANCE_STORAGE_KEY)});
    if (!raw) return;
    var data = JSON.parse(raw);
    if (!data || data.version !== ${APPEARANCE_VERSION} || !data.settings) return;
    var s = data.settings, root = document.documentElement;
    var pick = function (value, list) { return typeof value === 'string' && list.indexOf(value) > -1; };
    if (typeof s.themeId === 'string' && Object.prototype.hasOwnProperty.call(T, s.themeId)) {
      root.setAttribute('data-theme', s.themeId);
      for (var i = 0; i < N.length; i++) root.style.setProperty(N[i], T[s.themeId][i]);
    }
    if (pick(s.uiStyle, ${JSON.stringify(UI_STYLES)})) root.setAttribute('data-ui', s.uiStyle);
    if (pick(s.font, ${JSON.stringify(FONT_PACKS)})) root.setAttribute('data-font', s.font);
    if (pick(s.background, ${JSON.stringify(BACKGROUND_STYLES)})) root.setAttribute('data-bg', s.background);
    var reduced = false;
    try { reduced = matchMedia('(prefers-reduced-motion: reduce)').matches; } catch {}
    if (s.reduceEffects === true || reduced) root.setAttribute('data-effects', 'off');
  } catch {}
})();
`;
};
